import { execSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"

function sh(cmd) {
  try {
    return execSync(cmd, { encoding: "utf8" }).trim()
  } catch {
    return ""
  }
}

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"))
const fullCommit = process.env.SOURCE_COMMIT || sh("git rev-parse HEAD")
const commit = fullCommit ? fullCommit.slice(0, 7) : ""
const branch = process.env.SOURCE_BRANCH || sh("git rev-parse --abbrev-ref HEAD") || ""
const builtAt = new Date().toISOString()

const ts = `// AUTO-GENERATED by scripts/gen-build-info.mjs — nie edytuj ręcznie
export const BUILD_INFO = ${JSON.stringify({ version: pkg.version, commit, branch, builtAt }, null, 2)} as const
`
writeFileSync(new URL("../src/lib/build-info.generated.ts", import.meta.url), ts)
console.log(`build info: v${pkg.version} ${commit || "?"} (${branch || "?"})`)
